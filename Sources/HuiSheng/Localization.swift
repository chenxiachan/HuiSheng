import Foundation
import Combine

enum AppLanguage: String, CaseIterable {
    case chinese = "zh-Hans", english = "en"
    static var current: AppLanguage {
        AppLanguage(rawValue: UserDefaults.standard.string(forKey: "interfaceLanguage") ?? "") ?? .chinese
    }
    var locale: Locale { Locale(identifier: rawValue) }
}

final class AppSettings: ObservableObject {
    static let shared = AppSettings()
    @Published var language: AppLanguage {
        didSet { UserDefaults.standard.set(language.rawValue, forKey: "interfaceLanguage") }
    }
    private init() { language = .current }
}

/// Only application-owned labels are localized. Meeting text and model responses are never passed here.
func L(_ key: String) -> String {
    AppLanguage.current == .english ? (englishStrings[key] ?? key) : key
}
func LF(_ key: String, _ arguments: CVarArg...) -> String {
    String(format: L(key), locale: AppLanguage.current.locale, arguments: arguments)
}

/// v0.2 stored these labels in Chinese. Keep the on-disk snapshot unchanged across language switches.
func localizedScope(_ stored: String) -> String {
    stored.components(separatedBy: " · ").map { L($0) }.joined(separator: " · ")
}

